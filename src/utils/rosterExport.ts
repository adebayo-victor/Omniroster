import type { Folder, Employee } from './db';
import { generateCSV, downloadCSV } from './csvExport';

export interface ScheduleRowItem {
  id: string;
  dateStr: string;
  dayOfWeek: string;
  formattedDate: string;
  shiftName: string;
  startTime: string;
  endTime: string;
  gracePeriodMinutes: number;
  assignedStaffNames: string[];
}

/**
 * Normalizes both 'simple_shift' (7-day view starting today)
 * and 'optimized_roster' (from generatedShifts) into a unified list of timetable entries.
 */
export function getFolderScheduleRows(folder: Folder, employees: Employee[]): ScheduleRowItem[] {
  const empMap = new Map(employees.map((e) => [e.id, e.fullName]));

  // Optimized CSP Roster
  if (folder.type === 'optimized_roster' && folder.generatedShifts && folder.generatedShifts.length > 0) {
    return folder.generatedShifts.map((shift, idx) => {
      const dateObj = new Date(shift.dateStr + 'T12:00:00');
      const dayOfWeek = !isNaN(dateObj.getTime())
        ? dateObj.toLocaleDateString('en-US', { weekday: 'long' })
        : '';
      const formattedDate =
        shift.formattedDate ||
        (!isNaN(dateObj.getTime())
          ? dateObj.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
          : shift.dateStr);

      const assignedStaffNames = (shift.staffAssigned || []).map(
        (id) => empMap.get(id) || id
      );

      return {
        id: shift.id || `shift-${idx}`,
        dateStr: shift.dateStr,
        dayOfWeek,
        formattedDate,
        shiftName: shift.type || 'Standard Shift',
        startTime: shift.startTime,
        endTime: shift.endTime,
        gracePeriodMinutes: shift.gracePeriodMinutes || 15,
        assignedStaffNames,
      };
    });
  }

  // Simple Shift: 7-day rolling timetable starting from today
  const rows: ScheduleRowItem[] = [];
  const assignedNames = (folder.assignedEmployeeIds || []).map(
    (id) => empMap.get(id) || id
  );
  const today = new Date();

  for (let i = 0; i < 7; i++) {
    const cur = new Date(today);
    cur.setDate(today.getDate() + i);
    const dateStr = cur.toISOString().split('T')[0];
    const dayOfWeek = cur.toLocaleDateString('en-US', { weekday: 'long' });
    const formattedDate = cur.toLocaleDateString('en-US', {
      weekday: 'short',
      month: 'short',
      day: 'numeric',
    });

    rows.push({
      id: `simple-${dateStr}-${i}`,
      dateStr,
      dayOfWeek,
      formattedDate,
      shiftName: folder.name || 'Fixed Shift',
      startTime: folder.startTime || '09:00',
      endTime: 'Fixed Schedule',
      gracePeriodMinutes: folder.gracePeriodMinutes || 15,
      assignedStaffNames: assignedNames,
    });
  }

  return rows;
}

/**
 * Format 1: Beautifully formatted clipboard text with emojis for WhatsApp, Email, or SMS.
 */
export function formatRosterForClipboard(folder: Folder, employees: Employee[]): string {
  const rows = getFolderScheduleRows(folder, employees);
  const isRoster = folder.type === 'optimized_roster';
  const typeLabel = isRoster ? 'Optimized Multi-Shift Roster' : 'Standard 7-Day Shift';

  const dateScope =
    rows.length > 0 ? `${rows[0].dateStr} to ${rows[rows.length - 1].dateStr}` : 'Current Schedule';

  const lines: string[] = [];
  lines.push(`📋 *OmniRoster OS — Timetable Schedule*`);
  lines.push(`📂 *Folder:* ${folder.name}`);
  lines.push(`🔹 *Type:* ${typeLabel}`);
  lines.push(`🗓️ *Horizon:* ${dateScope}`);
  lines.push(`──────────────────────────────\n`);

  rows.forEach((row, idx) => {
    lines.push(`📅 *${row.dayOfWeek}, ${row.formattedDate}*`);
    lines.push(`🔹 *Shift:* ${row.shiftName}`);
    lines.push(
      `⏰ *Time:* ${row.startTime}${row.endTime && row.endTime !== 'Fixed Schedule' ? ` – ${row.endTime}` : ''} (±${row.gracePeriodMinutes}m grace)`
    );

    if (row.assignedStaffNames.length > 0) {
      lines.push(`👤 *Assigned Staff (${row.assignedStaffNames.length}):*`);
      row.assignedStaffNames.forEach((name) => {
        lines.push(`   • ${name}`);
      });
    } else {
      lines.push(`👤 *Assigned Staff:* _(No staff assigned)_`);
    }

    if (idx < rows.length - 1) {
      lines.push('');
    }
  });

  lines.push(`\n──────────────────────────────`);
  lines.push(`✨ *Generated by OmniRoster OS* • Secure Biometric Attendance`);

  return lines.join('\n');
}

/**
 * Copies formatted roster text to clipboard with iframe safety fallback.
 */
export async function copyRosterToClipboard(folder: Folder, employees: Employee[]): Promise<boolean> {
  const text = formatRosterForClipboard(folder, employees);

  try {
    if (navigator?.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch (err) {
    console.warn('[copyRosterToClipboard] Clipboard API failed, attempting textarea fallback:', err);
  }

  // Fallback for sandboxed iframes
  try {
    const textArea = document.createElement('textarea');
    textArea.value = text;
    textArea.style.position = 'fixed';
    textArea.style.left = '-9999px';
    textArea.style.top = '-9999px';
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch (fallbackErr) {
    console.error('[copyRosterToClipboard] All clipboard methods failed:', fallbackErr);
    return false;
  }
}

/**
 * Format 3: RFC-4180 Compliant CSV generation for Excel / Payroll.
 */
export function generateFolderRosterCSV(folder: Folder, employees: Employee[]): string {
  const rows = getFolderScheduleRows(folder, employees);

  const headers = [
    'Date',
    'Day of Week',
    'Shift Name',
    'Start Time',
    'End Time',
    'Grace Period (Mins)',
    'Assigned Staff',
    'Staff Count',
  ];

  const dataRows = rows.map((r) => [
    r.dateStr,
    r.dayOfWeek,
    r.shiftName,
    r.startTime,
    r.endTime,
    r.gracePeriodMinutes,
    r.assignedStaffNames.join('; '),
    r.assignedStaffNames.length,
  ]);

  return generateCSV(headers, dataRows);
}

/**
 * Triggers browser download of the CSV timetable.
 */
export function downloadFolderRosterCSV(folder: Folder, employees: Employee[]): void {
  const csvContent = generateFolderRosterCSV(folder, employees);
  const cleanName = (folder.name || 'roster')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  const today = new Date().toISOString().split('T')[0];
  const filename = `${cleanName}-schedule-${today}.csv`;

  downloadCSV(filename, csvContent);
}
